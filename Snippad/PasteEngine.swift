import AppKit
import ApplicationServices

extension NSPasteboard.PasteboardType {
    /// Markers from nspasteboard.org that clipboard managers -- Snippad's own
    /// history included -- honour by not recording the item.
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// Set on everything Snippad puts on the clipboard, so its history knows
    /// the change was its own.
    static let snippadSource = NSPasteboard.PasteboardType("dev.verhas.snippad.source")
    /// Set by macOS on what came through Universal Clipboard from another
    /// device.
    static let remoteClipboard = NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")
    /// What iPhone and iPad apps put on the clipboard.
    static let uikitAttributedString = NSPasteboard.PasteboardType("com.apple.uikit.attributedstring")
}

/// What happens to a value after it is on the clipboard.
struct PasteRules: Equatable, Sendable {
    /// Seconds until the value is taken off the clipboard.
    var expires: Int?
    /// Take the value off once an app has pasted it.
    var once = false
    /// A password: concealed from other clipboard managers, shown as dots in
    /// Snippad's history.
    var password = false
    /// The history list the value is recorded in, by name or id; nil is the
    /// default list.
    var list: String?
    /// Put this on the clipboard once the value has been pasted.
    var next: (@MainActor @Sendable () -> (types: [String: Data], name: String, rules: PasteRules)?)?

    static func == (a: PasteRules, b: PasteRules) -> Bool {
        a.expires == b.expires && a.once == b.once && a.password == b.password && a.list == b.list
            && (a.next == nil) == (b.next == nil)
    }

    var needsPasteDetection: Bool { once || next != nil }
}

extension Snippet {
    /// The rules of this snippet, with `next` looked up among the snippets of
    /// the same file.
    func rules(in all: [Snippet]) -> PasteRules {
        var rules = PasteRules(expires: expires, once: once, password: password, list: list)
        if let nextName = next, let target = all.first(where: { $0.name == nextName }) {
            rules.next = { (target.pasteboardTypes, target.name, target.rules(in: all)) }
        }
        return rules
    }

    /// One line for tooltips and lists; dots for a password.
    var preview: String {
        if password { return ClipItem.mask }
        switch kind {
        case .text: return value
        case .rich: return NSAttributedString(rtf: Data(value.utf8), documentAttributes: nil)?.string ?? ""
        case .file: return value
        case .image: return "Image"
        }
    }

    /// What goes on the clipboard for the snippet, by pasteboard type: its
    /// text; its rich text with the plain text; a reference to its file; or
    /// its image.
    var pasteboardTypes: [String: Data] {
        typealias T = NSPasteboard.PasteboardType
        switch kind {
        case .text:
            return [T.string.rawValue: Data(value.utf8)]
        case .rich:
            let rtf = Data(value.utf8)
            let plain = NSAttributedString(rtf: rtf, documentAttributes: nil)?.string ?? value
            return [T.rtf.rawValue: rtf, T.string.rawValue: Data(plain.utf8)]
        case .file:
            let url = URL(fileURLWithPath: (value as NSString).expandingTildeInPath)
            return [T.fileURL.rawValue: Data(url.absoluteString.utf8)]
        case .image:
            guard let data = Data(base64Encoded: value, options: .ignoreUnknownCharacters) else { return [:] }
            var out = [T.png.rawValue: data]
            if let tiff = NSImage(data: data)?.tiffRepresentation { out[T.tiff.rawValue] = tiff }
            return out
        }
    }
}

/// Puts things on the general pasteboard and enforces expiry, paste-once and
/// chains.
///
/// macOS does not say when something is pasted, and reading the clipboard is
/// not a paste either: IDEs, Universal Clipboard and clipboard managers read
/// every change within a fraction of a second. So a paste is a ⌘V typed while
/// Snippad's value is on the clipboard (PasteInterceptor), or one Snippad
/// sends itself. Values with paste-once or chain rules, and passwords, are
/// marked transient and concealed, so other clipboard managers that honour
/// the nspasteboard.org markers do not record them. Snippad records them
/// itself, through `recorder`.
@MainActor
@Observable
final class PasteEngine {
    static let shared = PasteEngine()

    /// In the unit tests a pasteboard of their own, so they never change
    /// the user's clipboard.
    var pasteboard = SnippadHome.isTesting ? NSPasteboard(name: .init("SnippadTests-\(UUID().uuidString)")) : NSPasteboard.general

    /// What Snippad last put on the clipboard and that is still there, for
    /// the status menu.
    private(set) var current: (name: String, rules: PasteRules)?

    /// The pasteboard change count right after Snippad's last write.
    @ObservationIgnored private(set) var ownChangeCount = -1
    /// Bumped on every write, so timers and paste follow-ups of an earlier
    /// value do nothing to a later one.
    @ObservationIgnored private var generation = 0
    @ObservationIgnored private var expiryTask: Task<Void, Never>?

    /// Called after a value with rules was pasted, with its name.
    @ObservationIgnored var onPasted: ((String) -> Void)?
    /// Gets a history entry for every text Snippad puts on the clipboard.
    @ObservationIgnored var recorder: ((ClipItem) -> Void)?
    /// Called whenever what is on the clipboard may have changed whether a
    /// paste is awaited: the keyboard tap follows it.
    @ObservationIgnored var onStateChange: (() -> Void)?

    /// How long after ⌘V the clipboard is changed: the app pasting has to
    /// read it first.
    static let pasteDelay: Duration = .milliseconds(400)

    /// Puts text on the clipboard under `rules`.
    func put(_ value: String, name: String, rules: PasteRules = PasteRules()) {
        put(types: [NSPasteboard.PasteboardType.string.rawValue: Data(value.utf8)], name: name, rules: rules)
    }

    /// Puts a snippet's value -- text, rich text, a file or an image -- on
    /// the clipboard under `rules`.
    func put(types: [String: Data], name: String, rules: PasteRules = PasteRules()) {
        generation += 1
        let gen = generation
        expiryTask?.cancel()
        expiryTask = nil

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        for (type, data) in types { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
        item.setData(Data(), forType: .snippadSource)
        if rules.needsPasteDetection || rules.password {
            item.setData(Data(), forType: .transient)
            item.setData(Data(), forType: .concealed)
        }
        pasteboard.writeObjects([item])
        ownChangeCount = pasteboard.changeCount
        current = (name, rules)

        var entry = ClipItem(items: [types])
        entry.label = name
        entry.password = rules.password ? true : nil
        entry.listID = rules.list
        recorder?(entry)
        onStateChange?()
        SnippadSound.copied()

        if let seconds = rules.expires {
            expiryTask = Task { [weak self] in
                try? await Task.sleep(for: .seconds(seconds))
                guard !Task.isCancelled else { return }
                self?.clear(ifGeneration: gen)
            }
        }
    }

    /// Puts pasteboard items back on the clipboard as they were captured.
    func put(items: [[NSPasteboard.PasteboardType: Data]], name: String, concealed: Bool = false) {
        generation += 1
        expiryTask?.cancel()
        expiryTask = nil

        pasteboard.clearContents()
        let objects = items.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            item.setData(Data(), forType: .snippadSource)
            if concealed { item.setData(Data(), forType: .concealed) }
            return item
        }
        pasteboard.writeObjects(objects)
        ownChangeCount = pasteboard.changeCount
        current = (name, PasteRules(password: concealed))
        onStateChange?()
        SnippadSound.copied()
    }

    /// Empties the clipboard, whatever is on it.
    func clear() {
        generation += 1
        expiryTask?.cancel()
        pasteboard.clearContents()
        ownChangeCount = pasteboard.changeCount
        current = nil
        onStateChange?()
    }

    /// Something else was copied: Snippad's value, and any chain, is gone.
    func clipboardChangedElsewhere() {
        guard current != nil, !holdsOwnValue else { return }
        generation += 1
        expiryTask?.cancel()
        current = nil
        onStateChange?()
    }

    /// Whether the clipboard still holds what Snippad last wrote.
    var holdsOwnValue: Bool {
        pasteboard.changeCount == ownChangeCount
    }

    /// Whether the value on the clipboard waits for a paste to move on.
    var awaitsPaste: Bool {
        holdsOwnValue && current?.rules.needsPasteDetection == true
    }

    /// A ⌘V was typed (or sent). If Snippad's value with rules is on the
    /// clipboard, it is replaced by the next one of its chain, or taken off,
    /// once the app pasting has had time to read it.
    func noticePaste() {
        guard awaitsPaste, let current else { return }
        let gen = generation
        Task { [weak self] in
            try? await Task.sleep(for: Self.pasteDelay)
            self?.pasted(generation: gen, name: current.name, rules: current.rules)
        }
    }

    private func clear(ifGeneration gen: Int) {
        guard gen == generation else { return }
        if holdsOwnValue {
            clear()
        } else {
            current = nil
            onStateChange?()
        }
    }

    private func pasted(generation gen: Int, name: String, rules: PasteRules) {
        guard gen == generation, holdsOwnValue else { return }
        onPasted?(name)
        if let next = rules.next?() {
            put(types: next.types, name: next.name, rules: next.rules)
        } else if rules.once {
            clear()
        }
    }
}
